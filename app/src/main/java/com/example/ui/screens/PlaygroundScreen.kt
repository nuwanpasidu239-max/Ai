            }

            Spacer(modifier = Modifier.height(20.dp))
            Icon(Icons.Default.WbSunny, contentDescription = null, tint = Color(0xFFFFD54F), modifier = Modifier.size(64.dp))
            Spacer(modifier = Modifier.height(8.dp))
