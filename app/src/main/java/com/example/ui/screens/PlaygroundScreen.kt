@Composable
fun PlaygroundScreen(
    steps: Int,
    onAddSteps: () -> Unit,
    onResetSteps: () -> Unit,
    todos: List<Pair<String, Boolean>>,
    onToggleTodo: (Int) -> Unit,
    onAddTodo: (String) -> Unit,
    cartItems: List<Pair<String, Double>>,
    onAddToCart: (String, Double) -> Unit,
    onClearCart: () -> Unit,
    isSinhala: Boolean,
    modifier: Modifier = Modifier
) {
    var selectedSandboxTab by remember { mutableIntStateOf(0) }
    val tabs = if (isSinhala) {
        listOf("ක්‍රියාකාරී Tracker", "Todo යෙදුම", "Store කූඩය", "කාලගුණය")
    } else {
        listOf("Fitness Step", "Todo Planner", "Mini Store", "Live Weather")
    }

    Column(
        modifier = modifier
            .fillMaxSize()
            .padding(16.dp)
    ) {
        // Playground Header
        Card(
            shape = RoundedCornerShape(16.dp),
            colors = CardDefaults.cardColors(containerColor = Color(0xFF131B2E)),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(modifier = Modifier.padding(16.dp)) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(
                        imageVector = Icons.Default.PlayCircle,
                        contentDescription = null,
                        tint = PrimaryCyan,
                        modifier = Modifier.size(24.dp)
                    )
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(
                        text = if (isSinhala) "සජීවී Jetpack Compose Playground" else "Live Compose Playground",
                        style = MaterialTheme.typography.titleMedium.copy(fontWeight = FontWeight.Bold),
                        color = Color.White
                    )
                }
                Text(
                    text = if (isSinhala)
                        "AI මඟින් නිර්මාණය කරන ලද Compose UI සංරචක සජීවීව පරීක්ෂා කර අත්හදා බලන්න."
                    else
                        "Interact with live simulated Android widgets generated by the AI architecture engine.",
                    style = MaterialTheme.typography.bodySmall,
                    color = Color(0xFF94A3B8),
                    modifier = Modifier.padding(top = 4.dp)
                )
            }
        }

        Spacer(modifier = Modifier.height(12.dp))

        // Tabs
        ScrollableTabRow(
            selectedTabIndex = selectedSandboxTab,
            containerColor = Color.Transparent,
            contentColor = PrimaryCyan,
            edgePadding = 0.dp,
            divider = {}
        ) {
            tabs.forEachIndexed { index, title ->
                Tab(
                    selected = selectedSandboxTab == index,
                    onClick = { selectedSandboxTab = index },
                    text = {
                        Text(
                            text = title,
                            fontWeight = if (selectedSandboxTab == index) FontWeight.Bold else FontWeight.Normal,
                            color = if (selectedSandboxTab == index) PrimaryCyan else Color(0xFF94A3B8)
                        )
                    }
                )
            }
        }

        Spacer(modifier = Modifier.height(16.dp))

        // Tab Content
        Box(
            modifier = Modifier
                .fillMaxSize()
                .weight(1f)
        ) {
            when (selectedSandboxTab) {
                0 -> FitnessSandbox(steps, onAddSteps, onResetSteps, isSinhala)
                1 -> TodoSandbox(todos, onToggleTodo, onAddTodo, isSinhala)
                2 -> StoreSandbox(cartItems, onAddToCart, onClearCart, isSinhala)
                3 -> WeatherSandbox(isSinhala)
            }
        }
    }
}

@Composable
private fun FitnessSandbox(
    steps: Int,
    onAddSteps: () -> Unit,
    onResetSteps: () -> Unit,
    isSinhala: Boolean
) {
    val progress = (steps / 10000f).coerceIn(0f, 1f)
    val animatedProgress by animateFloatAsState(targetValue = progress, label = "stepProgress")

    Card(
        shape = RoundedCornerShape(20.dp),
        colors = CardDefaults.cardColors(containerColor = Color(0xFF111827)),
        modifier = Modifier
            .fillMaxWidth()
            .border(1.dp, Color(0xFF1E293B), RoundedCornerShape(20.dp))
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(24.dp),
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            Text(
                text = if (isSinhala) "දෛනික පියවර ඉලක්කය" else "Daily Step Tracker Ring",
                style = MaterialTheme.typography.titleMedium.copy(fontWeight = FontWeight.Bold),
                color = Color.White
            )

            Spacer(modifier = Modifier.height(24.dp))

            Box(contentAlignment = Alignment.Center, modifier = Modifier.size(180.dp)) {
                CircularProgressIndicator(
                    progress = { 1f },
                    modifier = Modifier.fillMaxSize(),
                    color = Color(0xFF1F2937),
                    strokeWidth = 14.dp
                )
                CircularProgressIndicator(
                    progress = { animatedProgress },
                    modifier = Modifier.fillMaxSize(),
                    color = NeonEmerald,
                    strokeWidth = 14.dp
                )
                Column(horizontalAlignment = Alignment.CenterHorizontally) {
                    Text(
                        text = "$steps",
                        style = MaterialTheme.typography.headlineLarge.copy(fontWeight = FontWeight.ExtraBold),
                        color = Color.White
                    )
                    Text(
                        text = "/ 10,000 steps",
                        style = MaterialTheme.typography.bodySmall,
                        color = Color(0xFF94A3B8)
                    )
                }
            }

            Spacer(modifier = Modifier.height(24.dp))

            Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                Button(
                    onClick = onAddSteps,
                    colors = ButtonDefaults.buttonColors(containerColor = NeonEmerald, contentColor = Color(0xFF003920)),
                    shape = RoundedCornerShape(12.dp),
                    modifier = Modifier.testTag("add_steps_button")
                ) {
                    Icon(Icons.Default.DirectionsWalk, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(modifier = Modifier.width(6.dp))
                    Text("+500 Steps Walked", fontWeight = FontWeight.Bold)
                }
                OutlinedButton(
                    onClick = onResetSteps,
                    shape = RoundedCornerShape(12.dp),
                    modifier = Modifier.testTag("reset_steps_button")
                ) {
                    Text("Reset")
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .background(Color(0xFF1A2234), RoundedCornerShape(12.dp))
                    .padding(12.dp),
                horizontalArrangement = Arrangement.SpaceAround
            ) {
                Column(horizontalAlignment = Alignment.CenterHorizontally) {
                    Text(text = "🔥 Calories", style = MaterialTheme.typography.labelSmall, color = Color(0xFF94A3B8))
                    Text(text = "${(steps * 0.04).toInt()} kcal", fontWeight = FontWeight.Bold, color = Color.White)
                }
                Column(horizontalAlignment = Alignment.CenterHorizontally) {
                    Text(text = "📍 Distance", style = MaterialTheme.typography.labelSmall, color = Color(0xFF94A3B8))
                    Text(text = String.format("%.2f km", steps * 0.00076), fontWeight = FontWeight.Bold, color = Color.White)
                }
                Column(horizontalAlignment = Alignment.CenterHorizontally) {
                    Text(text = "⏱️ Active Time", style = MaterialTheme.typography.labelSmall, color = Color(0xFF94A3B8))
                    Text(text = "${steps / 100} mins", fontWeight = FontWeight.Bold, color = Color.White)
                }
            }
        }
    }
}

@Composable
private fun TodoSandbox(
    todos: List<Pair<String, Boolean>>,
    onToggleTodo: (Int) -> Unit,
    onAddTodo: (String) -> Unit,
    isSinhala: Boolean
) {
    var newTodoText by remember { mutableStateOf("") }

    Card(
        shape = RoundedCornerShape(20.dp),
        colors = CardDefaults.cardColors(containerColor = Color(0xFF111827)),
        modifier = Modifier
            .fillMaxSize()
            .border(1.dp, Color(0xFF1E293B), RoundedCornerShape(20.dp))
    ) {
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(16.dp)
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically
            ) {
                OutlinedTextField(
                    value = newTodoText,
                    onValueChange = { newTodoText = it },
                    placeholder = { Text(if (isSinhala) "නව කාර්යයක් එක් කරන්න..." else "New task...") },
                    modifier = Modifier
                        .weight(1f)
                        .testTag("new_todo_input"),
                    shape = RoundedCornerShape(12.dp),
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedBorderColor = PrimaryCyan,
                        unfocusedBorderColor = Color(0xFF374151)
                    )
                )
                Spacer(modifier = Modifier.width(8.dp))
                IconButton(
                    onClick = {
                        if (newTodoText.isNotBlank()) {
                            onAddTodo(newTodoText)
                            newTodoText = ""
                        }
                    },
                    modifier = Modifier
                        .clip(CircleShape)
                        .background(PrimaryCyan)
                        .testTag("add_todo_button")
                ) {
                    Icon(Icons.Default.Add, contentDescription = "Add", tint = Color(0xFF00363D))
                }
            }

            Spacer(modifier = Modifier.height(12.dp))

            LazyColumn(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                itemsIndexed(todos) { index, (task, done) ->
                    Card(
                        shape = RoundedCornerShape(12.dp),
                        colors = CardDefaults.cardColors(
                            containerColor = if (done) Color(0xFF1F2937).copy(alpha = 0.5f) else Color(0xFF1A2234)
                        ),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(horizontal = 12.dp, vertical = 8.dp)
                        ) {
                            Checkbox(
                                checked = done,
                                onCheckedChange = { onToggleTodo(index) },
                                colors = CheckboxDefaults.colors(checkedColor = NeonEmerald)
                            )
                            Spacer(modifier = Modifier.width(8.dp))
                            Text(
                                text = task,
                                style = MaterialTheme.typography.bodyMedium.copy(
                                    fontWeight = if (done) FontWeight.Normal else FontWeight.Medium
                                ),
                                color = if (done) Color(0xFF6B7280) else Color.White,
                                modifier = Modifier.weight(1f)
                            )
                            if (done) {
                                Icon(
                                    Icons.Default.CheckCircle,
                                    contentDescription = "Completed",
                                    tint = NeonEmerald,
                                    modifier = Modifier.size(18.dp)
                                )
                            }
                        }
                    }
                }
            }
        }
    }
}

@Composable
private fun StoreSandbox(
    cartItems: List<Pair<String, Double>>,
    onAddToCart: (String, Double) -> Unit,
    onClearCart: () -> Unit,
    isSinhala: Boolean
) {
    val total = cartItems.sumOf { it.second }
    val catalog = listOf(
        "Pixel 9 Pro Fold" to 1799.0,
        "Tensor Wireless Buds" to 199.0,
        "Android Dev Cap" to 29.0
    )

    Card(
        shape = RoundedCornerShape(20.dp),
        colors = CardDefaults.cardColors(containerColor = Color(0xFF111827)),
        modifier = Modifier
            .fillMaxSize()
            .border(1.dp, Color(0xFF1E293B), RoundedCornerShape(20.dp))
    ) {
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(16.dp)
        ) {
            Text(
                text = if (isSinhala) "නිෂ්පාදන ලැයිස්තුව (Catalog)" else "Product Catalog",
                style = MaterialTheme.typography.titleMedium.copy(fontWeight = FontWeight.Bold),
                color = Color.White
            )

            Spacer(modifier = Modifier.height(8.dp))

            catalog.forEach { (name, price) ->
                Card(
                    shape = RoundedCornerShape(12.dp),
                    colors = CardDefaults.cardColors(containerColor = Color(0xFF1A2234)),
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(vertical = 4.dp)
                ) {
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(12.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Column(modifier = Modifier.weight(1f)) {
                            Text(text = name, fontWeight = FontWeight.Bold, color = Color.White)
                            Text(text = "$$price", color = PrimaryCyan, style = MaterialTheme.typography.bodySmall)
                        }
                        Button(
                            onClick = { onAddToCart(name, price) },
                            shape = RoundedCornerShape(8.dp),
                            colors = ButtonDefaults.buttonColors(containerColor = PrimaryCyan, contentColor = Color(0xFF00363D))
                        ) {
                            Text("Add to Cart")
                        }
                    }
                }
            }

            Spacer(modifier = Modifier.height(16.dp))
            HorizontalDivider(color = Color(0xFF374151))
            Spacer(modifier = Modifier.height(16.dp))

            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Column {
                    Text(
                        text = if (isSinhala) "කූඩයේ අයිතම: ${cartItems.size}" else "Cart Items: ${cartItems.size}",
                        style = MaterialTheme.typography.bodySmall,
                        color = Color(0xFF94A3B8)
                    )
                    Text(
                        text = "Total: $${String.format("%.2f", total)}",
                        style = MaterialTheme.typography.titleLarge.copy(fontWeight = FontWeight.ExtraBold),
                        color = NeonEmerald
                    )
                }
                if (cartItems.isNotEmpty()) {
                    OutlinedButton(onClick = onClearCart) {
                        Text("Clear Cart")
                    }
                }
            }
        }
    }
}

@Composable
private fun WeatherSandbox(isSinhala: Boolean) {
