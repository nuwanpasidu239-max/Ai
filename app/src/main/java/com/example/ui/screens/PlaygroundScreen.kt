            Text(text = "Sunny & Clear Skies", color = Color(0xFF94A3B8))

            Spacer(modifier = Modifier.height(20.dp))

            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .background(Color(0xFF132238), RoundedCornerShape(12.dp))
